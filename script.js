// Eating behavior calculation:
const eatingBehav = dog => {
  if (dog.curFood >= dog.recFood * 0.9 && dog.curFood <= dog.recFood * 1.1)
    return 'OK';
  else if (dog.curFood > dog.recFood) return 'Too much';
  else return 'Too little';
};

